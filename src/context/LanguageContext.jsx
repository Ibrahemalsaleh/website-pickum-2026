// إنشاء سياق اللغة
const LanguageContext = createContext();

// مقدم سياق اللغة
export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState('ar');
  const [isLoading, setIsLoading] = useState(true);

  // تحميل اللغة المحفوظة عند بدء التطبيق
  useEffect(() => {
    const savedLanguage = localStorage.getItem('ahlan-Pickum-language');
    if (savedLanguage && ['ar', 'en'].includes(savedLanguage)) {
      setLanguage(savedLanguage);
    }
    
    // تطبيق اتجاه النص
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = language;
    
    setIsLoading(false);
  }, [language]);

  // دالة تغيير اللغة
  const changeLanguage = (newLanguage) => {
    if (['ar', 'en'].includes(newLanguage)) {
      setLanguage(newLanguage);
      localStorage.setItem('ahlan-Pickum-language', newLanguage);
      
      // تطبيق التغييرات على العنصر الجذر
      document.documentElement.dir = newLanguage === 'ar' ? 'rtl' : 'ltr';
      document.documentElement.lang = newLanguage;
      
      // تحديث عنوان الصفحة
      const titles = {
        ar: 'أهلا بكم للنقل والتوصيل - خدمات نقل احترافية في الأردن',
        en: 'Ahlan Pickum Transport - Professional Transport Services in Jordan'
      };
      document.title = titles[newLanguage];
    }
  };

  // دالة الترجمة
  const t = (key) => {
    const keys = key.split('.');
    let value = translations[language];
    
    for (const k of keys) {
      if (value && typeof value === 'object' && k in value) {
        value = value[k];
      } else {
        console.warn(`Translation key not found: ${key} for language: ${language}`);
        return key;
      }
    }
    
    return value || key;
  };

  // دالة للحصول على النص باتجاه الصحيح
  const getDirection = () => language === 'ar' ? 'rtl' : 'ltr';
  
  // دالة للحصول على محاذاة النص
  const getTextAlign = () => language === 'ar' ? 'right' : 'left';

  // دالة للحصول على اتجاه الفليكس
  const getFlexDirection = (reverse = false) => {
    if (language === 'ar') {
      return reverse ? 'row' : 'row-reverse';
    }
    return reverse ? 'row-reverse' : 'row';
  };

  // قيم السياق
  const contextValue = {
    language,
    changeLanguage,
    t,
    isLoading,
    isRTL: language === 'ar',
    isLTR: language === 'en',
    getDirection,
    getTextAlign,
    getFlexDirection,
    translations: translations[language]
  };

  if (isLoading) {
    return (
      <div className="language-loading">
        <div className="loading-spinner">
          <div className="spinner-ring"></div>
        </div>
        <p>جاري تحميل اللغة...</p>
        
        <style jsx>{`
          .language-loading {
            position: fixed;
            top: 0;
            left: 0;
            width: 100%;
            height: 100vh;
            background: linear-gradient(135deg, #1e5631 0%, #2a7d46 100%);
            display: flex;
            flex-direction: column;
            align-items: center;
            justify-content: center;
            color: white;
            z-index: 9999;
          }

          .loading-spinner {
            margin-bottom: 20px;
          }

          .spinner-ring {
            width: 60px;
            height: 60px;
            border: 4px solid rgba(255, 255, 255, 0.3);
            border-top: 4px solid #a4de02;
            border-radius: 50%;
            animation: spin 1s linear infinite;
          }

          @keyframes spin {
            0% { transform: rotate(0deg); }
            100% { transform: rotate(360deg); }
          }

          .language-loading p {
            font-size: 1.125rem;
            font-weight: 500;
            margin: 0;
          }
        `}</style>
      </div>
    );
  }

  return (
    <LanguageContext.Provider value={contextValue}>
      {children}
    </LanguageContext.Provider>
  );
};

// خطاف لاستخدام سياق اللغة
export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};

// خطاف لاستخدام الترجمة فقط
export const useTranslation = () => {
  const { t } = useLanguage();
  return t;
};

// خطاف للحصول على معلومات اللغة الحالية
export const useLanguageInfo = () => {
  const { language, isRTL, isLTR, getDirection, getTextAlign, getFlexDirection } = useLanguage();
  return {
    language,
    isRTL,
    isLTR,
    direction: getDirection(),
    textAlign: getTextAlign(),
    getFlexDirection
  };
};

// دالة مساعدة لدمج الكلاسات مع دعم RTL
export const combineClasses = (...classes) => {
  return classes.filter(Boolean).join(' ');
};

// دالة مساعدة للحصول على الكلاسات المناسبة للاتجاه
export const getDirectionalClasses = (baseClass, { isRTL } = {}) => {
  const { isRTL: contextRTL } = useLanguageInfo();
  const rtl = isRTL !== undefined ? isRTL : contextRTL;
  
  return {
    base: baseClass,
    rtl: rtl ? `${baseClass}-rtl` : `${baseClass}-ltr`,
    ltr: !rtl ? `${baseClass}-ltr` : `${baseClass}-rtl`
  };
};

